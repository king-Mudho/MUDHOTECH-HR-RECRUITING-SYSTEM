"""Generate the entity-relationship diagram from the Django models (P16-T04).

    python manage.py generate_erd --out ../docs/architecture/ERD.md

Writes one Mermaid ``erDiagram`` per domain app (fields with types, primary/foreign keys and
relations), so the documented schema is always the real one. No extra dependency (Graphviz /
django-extensions) is needed; GitHub and most Markdown viewers render Mermaid directly.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from django.apps import apps
from django.core.management.base import BaseCommand, CommandParser
from django.db import models

SKIP_APPS = {
    "admin",
    "auth",
    "contenttypes",
    "sessions",
    "sites",
    "django_celery_beat",
    "django_celery_results",
    "core_testapp",
}


def _type(field: models.Field[Any, Any]) -> str:
    name = field.get_internal_type()
    return {
        "ForeignKey": "uuid",
        "OneToOneField": "uuid",
        "UUIDField": "uuid",
        "CharField": "string",
        "TextField": "text",
        "SlugField": "string",
        "EmailField": "string",
        "URLField": "string",
        "JSONField": "json",
        "BooleanField": "bool",
        "DateTimeField": "datetime",
        "DateField": "date",
        "DecimalField": "decimal",
        "PositiveIntegerField": "int",
        "PositiveSmallIntegerField": "int",
        "IntegerField": "int",
        "BigIntegerField": "bigint",
        "FloatField": "float",
    }.get(name, name.replace("Field", "").lower() or "field")


def _entity(model: type[models.Model]) -> str:
    return f"{model._meta.app_label}_{model.__name__}".upper()


class Command(BaseCommand):
    help = "Write a Mermaid ER diagram of all domain models (docs/architecture/ERD.md)."

    def add_arguments(self, parser: CommandParser) -> None:
        parser.add_argument("--out", default="../docs/architecture/ERD.md")

    def handle(self, *args: Any, **options: Any) -> None:
        sections: list[str] = [
            "# Entity-relationship diagram",
            "",
            "Generated by `python manage.py generate_erd` from the Django models - do not edit by "
            "hand. Every table also has `id` (UUID), `created_at` and `updated_at`; tenant tables "
            "carry `organisation_id` and are protected by PostgreSQL row-level security.",
            "",
        ]
        for config in sorted(apps.get_app_configs(), key=lambda c: c.label):
            if config.label in SKIP_APPS or not config.name.startswith("apps."):
                continue
            model_list = [m for m in config.get_models() if not m._meta.proxy]
            if not model_list:
                continue
            lines = ["```mermaid", "erDiagram"]
            relations: list[str] = []
            for model in model_list:
                lines.append(f"    {_entity(model)} {{")
                for field in model._meta.concrete_fields:
                    if field.name in ("created_at", "updated_at"):
                        continue
                    marker = " PK" if field.primary_key else (" FK" if field.is_relation else "")
                    column = field.column if field.is_relation else field.name
                    lines.append(f"        {_type(field)} {column}{marker}")
                    target = field.related_model
                    if (
                        field.is_relation
                        and isinstance(target, type)
                        and target._meta.app_label == config.label
                    ):
                        kind = "||--||" if field.one_to_one else "}o--||"
                        relations.append(
                            f'    {_entity(model)} {kind} {_entity(target)} : "{field.name}"'
                        )
                lines.append("    }")
            lines = [*lines, *relations, "```", ""]
            sections += [f"## {config.verbose_name} (`{config.label}`)", "", *lines]
        out = Path(options["out"])
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(sections), encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"Wrote {out}"))
