import type { NextConfig } from "next";
import createNextIntlPlugin from "next-intl/plugin";

const withNextIntl = createNextIntlPlugin("./src/i18n/request.ts");

/** Django origin as seen from the Next.js server (docker: http://backend:8000). */
const API_INTERNAL_URL = process.env.API_INTERNAL_URL ?? "http://127.0.0.1:8000";

const isDev = process.env.NODE_ENV === "development";

/**
 * Content Security Policy (P09-T08, ADR-027). Nonce-based CSP is incompatible with Partial
 * Prerendering / Cache Components (Next.js docs), which the public job board relies on, so scripts
 * keep 'unsafe-inline' (no 'unsafe-eval' outside dev); every other directive is strict. Untrusted
 * text is never rendered as HTML (React escaping; job HTML sanitised server-side with nh3).
 */
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "worker-src 'self' blob:", // pdf.js worker (evidence viewer)
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  ...(isDev
    ? []
    : [
        { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains; preload" },
      ]),
];

const nextConfig: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  cacheComponents: true,
  partialPrefetching: true,
  // Django routes end with "/" - never let Next.js strip/redirect trailing slashes on /api.
  skipTrailingSlashRedirect: true,
  // Dev server only: allow opening the app via 127.0.0.1 (Windows localhost/IPv6 quirks, E2E).
  allowedDevOrigins: ["127.0.0.1", "localhost"],
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async rewrites() {
    // Same-origin API: session + CSRF cookies work without CORS (ADR-004).
    // The first rule preserves Django's trailing slash (otherwise Django answers 301 -> loop).
    return [
      { source: "/api/:path*/", destination: `${API_INTERNAL_URL}/api/:path*/` },
      { source: "/api/:path*", destination: `${API_INTERNAL_URL}/api/:path*` },
      { source: "/healthz", destination: `${API_INTERNAL_URL}/healthz` },
      // Public SEO artefacts are generated by Django from published vacancies (P03-T10).
      { source: "/sitemap.xml", destination: `${API_INTERNAL_URL}/api/v1/sitemap.xml` },
      { source: "/jobs/feed.rss", destination: `${API_INTERNAL_URL}/api/v1/jobs/feed.rss` },
      { source: "/jobs/feed.json", destination: `${API_INTERNAL_URL}/api/v1/jobs/feed.json` },
    ];
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default withNextIntl(nextConfig);
